/**
 * cubic-reciprocity.ts - Cubic Reciprocity in the Eisenstein Integers
 *
 * The cubic residue character [alpha/pi] is the analogue of the Legendre
 * symbol in Z[omega], omega = exp(2*pi*i/3). For two primary Eisenstein
 * primes pi and rho the cubic reciprocity law states [pi/rho] = [rho/pi].
 * This module constructs primary primes above small rational primes p = 1 mod 3
 * and verifies the law pair by pair.
 *
 * Limit: exact arithmetic with small rational primes (default below 100).
 * Larger primes are possible but the search for a representative is O(p).
 *
 * Time:  O(k^2 * p) for k primes (enumerating candidates modulo p)
 * Space: O(k^2) for the character table
 */

import type { AlgorithmModule, VisualFrame, VisualEntity } from "@/types";

type Eis = [number, number];

const UNITS: Eis[] = [
    [1, 0],
    [-1, 0],
    [0, 1],
    [0, -1],
    [-1, -1],
    [1, 1],
];

function mod(n: number, m: number): number {
    return ((n % m) + m) % m;
}

function mul(a: Eis, b: Eis): Eis {
    return [a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0] - a[1] * b[1]];
}

function norm(a: Eis): number {
    return a[0] * a[0] - a[0] * a[1] + a[1] * a[1];
}

function powMod(base: number, exp: number, m: number): number {
    let result = 1;
    let b = mod(base, m);
    let e = exp;
    while (e > 0) {
        if (e % 2 === 1) result = (result * b) % m;
        b = (b * b) % m;
        e = Math.floor(e / 2);
    }
    return result;
}

function isPrimary(a: Eis): boolean {
    return mod(a[0], 3) === 2 && mod(a[1], 3) === 0;
}

function toPrimary(a: Eis): Eis | null {
    for (const u of UNITS) {
        const candidate = mul(a, u);
        if (isPrimary(candidate)) return candidate;
    }
    return null;
}

function findPrimaryPrime(p: number): Eis | null {
    const bound = Math.ceil(Math.sqrt(p)) + 1;
    for (let a = -bound; a <= bound; a += 1) {
        for (let b = -bound; b <= bound; b += 1) {
            if (norm([a, b]) === p) {
                const primary = toPrimary([a, b]);
                if (primary) return primary;
            }
        }
    }
    return null;
}

/** The root r of x^2+x+1 mod p whose kernel ideal is generated by pi. */
function rootForPrime(pi: Eis, p: number): number | null {
    for (let r = 0; r < p; r += 1) {
        if (mod(r * r + r + 1, p) === 0 && mod(pi[0] + pi[1] * r, p) === 0) return r;
    }
    return null;
}

/** Cubic character value as 0 (1), 1 (omega), or 2 (omega^2). */
function cubicChar(alpha: Eis, pi: Eis): number | null {
    const p = norm(pi);
    const r = rootForPrime(pi, p);
    if (r === null) return null;
    const x = mod(alpha[0] + alpha[1] * r, p);
    const k = powMod(x, Math.floor((p - 1) / 3), p);
    if (k === mod(1, p)) return 0;
    if (k === mod(r, p)) return 1;
    if (k === mod(r * r, p)) return 2;
    return null;
}

const CHAR_LABEL = ["1", "w", "w2"];

function* run(input: unknown): Generator<VisualFrame, void, unknown> {
    const task = (input as { primes?: number[] } | null) ?? {};
    const candidates = task.primes ?? [7, 13, 19, 31, 37, 43];
    const primes = candidates.filter((p) => p > 3 && p % 3 === 1);
    const primary = primes.map(findPrimaryPrime);

    let step = 0;
    const makeGrid = (focusI: number, focusJ: number, verdict: string): VisualEntity[] => {
        const entities: VisualEntity[] = [];
        for (let i = 0; i < primes.length; i += 1) {
            for (let j = 0; j < primes.length; j += 1) {
                const active = (i === focusI && j === focusJ) || (i === focusJ && j === focusI);
                const pi = primary[i];
                const rho = primary[j];
                const char = pi && rho ? cubicChar(pi, rho) : null;
                entities.push({
                    id: `cell-${i}-${j}`,
                    type: "cell",
                    label: i === j ? "-" : CHAR_LABEL[char ?? 0] ?? "?",
                    value: char ?? -1,
                    state: i === j ? "idle" : active ? "active" : "unvisited",
                    x: 0,
                    y: 0,
                    width: 0,
                    height: 0,
                    metadata: { row: i, col: j, i, j },
                });
            }
        }
        if (typeof verdict === "string" && entities.length > 0) {
            entities[0]!.metadata.verdict = verdict;
        }
        return entities;
    };

    yield {
        stepNumber: step,
        entities: makeGrid(-1, -1, "setup"),
        edges: [],
        description: `Construct primary Eisenstein primes above ${primes.length} rational primes congruent to 1 mod 3.`,
        codeLineNumber: 0,
        layout: "grid",
        meta: { rows: primes.length, cols: primes.length, primes, pairs: 0, failures: 0 },
    };
    step += 1;

    let pairs = 0;
    let failures = 0;
    for (let i = 0; i < primes.length; i += 1) {
        for (let j = i + 1; j < primes.length; j += 1) {
            const pi = primary[i];
            const rho = primary[j];
            const left = pi && rho ? cubicChar(pi, rho) : null;
            const right = pi && rho ? cubicChar(rho, pi) : null;
            const holds = left !== null && right !== null && left === right;
            if (!holds) failures += 1;
            pairs += 1;
            yield {
                stepNumber: step,
                entities: makeGrid(i, j, holds ? "holds" : "failed"),
                edges: [],
                description: `pi=${primes[i]}, rho=${primes[j]}: [pi/rho] = ${CHAR_LABEL[left ?? 0]}, [rho/pi] = ${CHAR_LABEL[right ?? 0]}, reciprocity ${holds ? "holds" : "fails"}.`,
                codeLineNumber: 3,
                layout: "grid",
                meta: {
                    rows: primes.length,
                    cols: primes.length,
                    i,
                    j,
                    left,
                    right,
                    holds,
                    pairs,
                    failures,
                },
            };
            step += 1;
        }
    }

    yield {
        stepNumber: step,
        entities: makeGrid(-1, -1, failures === 0 ? "verified" : "failed"),
        edges: [],
        description: `Cubic reciprocity verified on ${pairs} prime pairs with ${failures} failure(s).`,
        codeLineNumber: 6,
        layout: "grid",
        meta: { rows: primes.length, cols: primes.length, pairs, failures, verified: failures === 0 },
    };
}

