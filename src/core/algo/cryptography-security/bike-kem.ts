/**
 * bike-kem.ts - BIKE-Style QC-MDPC Syndrome Decoding (Toy, Exhaustive Decoder)
 *
 * ---------------------------------------------------------------------------
 * What it does
 * ---------------------------------------------------------------------------
 * BIKE is a code-based KEM whose security rests on decoding a quasi-cyclic
 * moderate-density parity-check code. A ciphertext is a syndrome obtained by
 * adding a small number of circulant columns of the parity-check matrix, and
 * the secret trapdoor lets the receiver find that small error and derive the
 * shared bit. This toy keeps the quasi-cyclic matrix and the sparse-error
 * structure exactly, but replaces BIKE's bit-flipping decoder with exhaustive
 * search over all weight-three errors so every step is verifiable. It is a
 * teaching model, not the BIKE specification.
 *
 * ---------------------------------------------------------------------------
 * Complexity
 *   Time:  O(n choose w) for the exhaustive toy decoder
 *   Space: O(n) for the syndrome and candidate error
 *
 * ---------------------------------------------------------------------------
 * Visualization mapping
 *   - Bars show the syndrome bits and the error weight being tested.
 *   - meta reports the syndrome, the shared bit, and whether decoding succeeded.
 */

import type { AlgorithmModule, EntityState, VisualEntity, VisualFrame } from "@/types";

const N = 16;
const WEIGHT = 3;

/** Column i of the circulant matrix generated by a sparse vector. */
export function column(seedVector: number[], index: number): number[] {
    return Array.from({ length: N }, (_, row) =>
        (seedVector[(row - index + N) % N] ?? 0) & 1,
    );
}

/** Sparse secret vector derived from a seed (exactly WEIGHT one bits). */
export function secretVector(seed: number): number[] {
    const result = new Array<number>(N).fill(0);
    let state = (seed >>> 0) || 1;
    let placed = 0;
    while (placed < WEIGHT) {
        state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
        const index = (state >>> 16) % N;
        if (result[index] === 0) {
            result[index] = 1;
            placed += 1;
        }
    }
    return result;
}

/** Sparse error vector with the same weight. */
export function errorVector(seed: number): number[] {
    return secretVector(seed ^ 0x5bd1e995);
}

/** Syndrome s = xor of the columns selected by the error vector. */
export function syndrome(seedVector: number[], error: number[]): number[] {
    const result = new Array<number>(N).fill(0);
    for (let i = 0; i < N; i += 1) {
        if (error[i] === 1) {
            const col = column(seedVector, i);
            for (let row = 0; row < N; row += 1) {
                result[row] = (result[row] ?? 0) ^ (col[row] ?? 0);
            }
        }
    }
    return result;
}

/** Shared bit derived from an error pattern by a deterministic fold. */
export function sharedBit(error: number[]): number {
    let h = 2166136261;
    for (const bit of error) {
        h = Math.imul(h ^ bit, 16777619) >>> 0;
    }
    return (h >>> 8) & 1;
}

const equalVectors = (a: number[], b: number[]): boolean => a.every((v, i) => v === (b[i] ?? -1));

/** Exhaustively recover a weight-WEIGHT error from its syndrome. */
export function decode(seedVector: number[], s: number[]): number[] | null {
    const candidates: number[] = [];
    for (let i = 0; i < N; i += 1) {
        for (let j = i + 1; j < N; j += 1) {
            for (let k = j + 1; k < N; k += 1) {
                candidates.push(i, j, k);
            }
        }
    }
    for (let c = 0; c < candidates.length; c += 3) {
        const error = new Array<number>(N).fill(0);
        error[candidates[c]!] = 1;
        error[candidates[c + 1]!] = 1;
        error[candidates[c + 2]!] = 1;
        if (equalVectors(syndrome(seedVector, error), s)) {
            return error;
        }
    }
    return null;
}

function makeBars(values: number[], active: number): VisualEntity[] {
    return values.map((value, index) => ({
        id: `val-${index}`,
        type: "bar" as const,
        label: String(value),
        value,
        state: (index === active ? "active" : "idle") as EntityState,
        x: 0,
        y: 0,
        width: 0,
        height: 0,
        metadata: { index, weight: index < WEIGHT ? 1 : 0 },
    }));
}

/** The BIKE-style generator. */
function* run(input: unknown): Generator<VisualFrame, void, unknown> {
    const task = (input as { keySeed?: number; messageSeed?: number } | null) ?? {};
    const keySeed = typeof task.keySeed === "number" ? Math.floor(task.keySeed) : 5;
    const messageSeed = typeof task.messageSeed === "number" ? Math.floor(task.messageSeed) : 9;
    const secretVectorValue = secretVector(keySeed);
    const error = errorVector(messageSeed);
    const s = syndrome(secretVectorValue, error);
    const bit = sharedBit(error);
    let step = 0;

    yield {
        stepNumber: step,
        entities: makeBars(secretVectorValue.slice(0, 8), 0),
        edges: [],
        description: `QC-MDPC toy: sparse parity-check columns from key seed ${keySeed}, weight ${WEIGHT}.`,
        codeLineNumber: 0,
        layout: "array",
        meta: { keySeed, syndrome: s.join(""), bit: 0, decoded: false },
    };
    step += 1;

    yield {
        stepNumber: step,
        entities: makeBars(s.slice(0, 8), 0),
        edges: [],
        description: `Encapsulate: xor the columns selected by a weight-${WEIGHT} error into the syndrome.`,
        codeLineNumber: 1,
        layout: "array",
        meta: { keySeed, syndrome: s.join(""), bit, decoded: false },
    };
    step += 1;

    const recovered = decode(secretVectorValue, s);
    yield {
        stepNumber: step,
        entities: makeBars(recovered?.slice(0, 8) ?? s.slice(0, 8), 0),
        edges: [],
        description: recovered
            ? `Decoding found a matching sparse error: ${recovered.map((v, i) => (v ? i : -1)).filter((v) => v >= 0).join(",")}.`
            : "No weight-three error reproduces the syndrome.",
        codeLineNumber: 2,
        layout: "array",
        meta: { keySeed, syndrome: s.join(""), bit, decoded: recovered !== null },
    };
    step += 1;

    const recoveredBit = recovered ? sharedBit(recovered) : -1;
    yield {
        stepNumber: step,
        entities: makeBars([bit, recoveredBit, ...s.slice(0, 6)], 0),
        edges: [],
        description: `Shared bit ${bit} versus recovered bit ${recoveredBit}; ${recoveredBit === bit ? "they agree" : "mismatch"}. Exhaustive toy decoder, not BIKE.`,
        codeLineNumber: 3,
        layout: "array",
        meta: { keySeed, syndrome: s.join(""), bit, recoveredBit, decoded: recovered !== null, agreed: recoveredBit === bit },
    };
}

