/**
 * hash-drbg.ts - Hash_DRBG Deterministic Random Bit Generator (Toy Hash)
 *
 * ---------------------------------------------------------------------------
 * What it does
 * ---------------------------------------------------------------------------
 * Hash_DRBG is a NIST SP 800-90A random bit generator built from a hash
 * function. Instantiation hashes the entropy, nonce, and personalization
 * string into working state V and a constant C. Each request hashes V to
 * produce output, then updates V by hashing 0x03 concatenated with V. Reseeding
 * mixes fresh entropy into both V and C with distinct domain separators. The
 * state machine and domain separators here match the standard, but the hash is
 * a small noninvertible toy mixer, so this is a teaching model and is not a
 * cryptographically secure random source.
 *
 * ---------------------------------------------------------------------------
 * Complexity
 *   Time:  O(count / digestSize) hashes per generate request
 *   Space: O(digestSize) for V, C, and the output block
 *
 * ---------------------------------------------------------------------------
 * Visualization mapping
 *   - Rows show the working state V, the constant C, and the generated bytes.
 *   - The output row fills as generate requests are served.
 */

import type { AlgorithmModule, EntityState, VisualEntity, VisualFrame } from "@/types";

function rotl32(value: number, shift: number): number {
    const n = shift & 31;
    return (((value << n) | (value >>> (32 - n))) >>> 0);
}

/** A small deterministic byte-mixing hash that returns sixteen bytes. */
export function toyHash(data: number[]): number[] {
    let a = 0x9e3779b9;
    let b = 0x85ebca6b;
    let c = 0xc2b2ae35;
    let d = 0x27d4eb2f;
    for (const byte of data) {
        a = rotl32(a ^ (byte & 0xff), 7) >>> 0;
        b = Math.imul(b ^ a, 0x01000193) >>> 0;
        c = (c + b + (a >>> 7)) >>> 0;
        d = rotl32(d ^ c, 11) >>> 0;
    }
    const out: number[] = [];
    for (const word of [a, b, c, d]) {
        out.push((word >>> 24) & 0xff, (word >>> 16) & 0xff, (word >>> 8) & 0xff, word & 0xff);
    }
    return out;
}

function nonceBytes(nonce: number): number[] {
    const n = nonce >>> 0;
    return [(n >>> 24) & 0xff, (n >>> 16) & 0xff, (n >>> 8) & 0xff, n & 0xff];
}

export class HashDrbg {
    v: number[];
    c: number[];
    reseedCounter: number;

    constructor(entropy: number[], nonce: number, personalization: number[] = []) {
        const seedMaterial = [...entropy, ...nonceBytes(nonce), ...personalization];
        this.v = toyHash([0x00, ...seedMaterial]);
        this.c = toyHash([0x01, ...this.v, ...seedMaterial]);
        this.reseedCounter = 1;
    }

    generate(count: number): number[] {
        const out: number[] = [];
        while (out.length < count) {
            out.push(...toyHash([0x02, ...this.v]));
            this.v = toyHash([0x03, ...this.v]);
        }
        this.reseedCounter += 1;
        return out.slice(0, count);
    }

    reseed(material: number[]): void {
        this.v = toyHash([0x04, ...this.v, ...material]);
        this.c = toyHash([0x05, ...this.v, ...material]);
        this.reseedCounter = 1;
    }
}

function rowCells(row: number, bytes: number[], state: EntityState, revealed: number): VisualEntity[] {
    return Array.from({ length: 16 }, (_, col) => {
        const value = bytes[col] ?? 0;
        return {
            id: `byte-${row}-${col}`,
            type: "cell" as const,
            label: value.toString(16).toUpperCase().padStart(2, "0"),
            value,
            state: col < revealed ? state : ("unvisited" as EntityState),
            x: 0,
            y: 0,
            width: 0,
            height: 0,
            metadata: { row, col },
        };
    });
}

function toHex(bytes: number[]): string {
    return bytes.map((b) => b.toString(16).toUpperCase().padStart(2, "0")).join("");
}

function* run(input: unknown): Generator<VisualFrame, void, unknown> {
    const task = (input as { entropy?: number[]; nonce?: number; personalization?: number[]; bytes?: number; reseedMaterial?: number[] } | null) ?? {};
    const entropy = Array.isArray(task.entropy) ? task.entropy : [5, 10, 15, 20];
    const nonce = typeof task.nonce === "number" ? task.nonce >>> 0 : 9;
    const personalization = Array.isArray(task.personalization) ? task.personalization : [1, 2];
    const bytes = typeof task.bytes === "number" ? Math.max(1, Math.min(64, task.bytes)) : 8;
    const reseedMaterial = Array.isArray(task.reseedMaterial) ? task.reseedMaterial : [99, 42];

    const drbg = new HashDrbg(entropy, nonce, personalization);
    const setupV = [...drbg.v];
    const setupC = [...drbg.c];
    const first = drbg.generate(bytes);
    const afterFirstV = [...drbg.v];
    const second = drbg.generate(bytes);
    const afterSecondV = [...drbg.v];
    drbg.reseed(reseedMaterial);
    const afterReseedV = [...drbg.v];
    const afterReseedC = [...drbg.c];
    const third = drbg.generate(bytes);

    let step = 0;
    const frame = (v: number[], c: number[], out: number[], description: string, line: number, phase: number): VisualFrame => ({
        stepNumber: step++,
        entities: [
            ...rowCells(0, v, "pivot", 16),
            ...rowCells(1, c, "idle", 16),
            ...rowCells(2, out, phase > 0 ? "sorted" : "active", Math.min(16, out.length)),
        ],
        edges: [],
        description,
        codeLineNumber: line,
        layout: "grid",
        meta: {
            rows: 3,
            cols: 16,
            entropy,
            nonce,
            bytes,
            reseedCounter: drbg.reseedCounter,
            setupV: toHex(setupV),
            setupC: toHex(setupC),
            first: toHex(first),
            second: toHex(second),
            postReseed: toHex(third),
        },
    });

    yield frame(setupV, setupC, [], "Instantiate: hash entropy, nonce, and personalization into V and C.", 0, 0);
    yield frame(afterFirstV, drbg.c, first, `Generate ${bytes} bytes by hashing V, then advance V.`, 1, 1);
    yield frame(afterSecondV, drbg.c, second, "Generate again from the advanced state, which gives different bytes.", 2, 1);
    yield frame(afterReseedV, afterReseedC, third, "Reseed with fresh entropy, then generate a new block.", 3, 1);
}

