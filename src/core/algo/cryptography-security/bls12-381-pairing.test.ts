/**
 * bls12-381-pairing.test.ts - Independent subgroup and pairing evaluation,
 * bilinearity/symmetry/nondegeneracy properties across inputs, frame shape,
 * and termination.
 */

import { describe, expect, it } from "vitest";
import mod from "./bls12-381-pairing";
import type { VisualFrame } from "@/types";

const P = 101;
const Q = 5;
const G = 2;
const H = 95;

function modp(v: number): number {
    return ((v % P) + P) % P;
}

function pow(base: number, exp: number): number {
    let r = 1;
    let b = modp(base);
    let e = exp;
    while (e > 0) {
        if (e & 1) r = modp(r * b);
        b = modp(b * b);
        e = Math.floor(e / 2);
    }
    return r;
}

function pairing(a: number, b: number): number {
    return pow(H, ((a * b) % Q + Q) % Q);
}

function checkFrames(frames: VisualFrame[]): void {
    expect(frames.length).toBeGreaterThan(0);
    frames.forEach((frame, index) => {
        expect(frame.stepNumber).toBe(index);
        expect(frame.layout).toBe("array");
        expect(frame.entities.length).toBe(11);
        expect(frame.entities.every((e) => e.type === "bar")).toBe(true);
        expect(frame.description.length).toBeGreaterThan(0);
        expect(frame.codeLineNumber).toBeGreaterThanOrEqual(0);
        expect(frame.codeLineNumber).toBeLessThan(mod.pseudocode?.length ?? 0);
        expect(frame.meta["p"]).toBe(P);
        expect(frame.meta["q"]).toBe(Q);
        expect(frame.meta["h"]).toBe(H);
    });
}

describe("ToyPairing", () => {
    it("uses a genuine order-q subgroup generated by h", () => {
        expect(pow(G, (P - 1) / Q)).toBe(H);
        expect(pow(H, Q)).toBe(1);
        expect(H).not.toBe(1);
    });

    it("matches an independent pairing evaluation on the default input", () => {
        const input = mod.defaultInput as { a: number; b: number };
        const frames = [...mod.run(input)];
        checkFrames(frames);
        const final = frames[frames.length - 1]?.meta;
        expect(final?.["Pval"]).toBe(pow(H, input.a));
        expect(final?.["Qval"]).toBe(pow(H, input.b));
        expect(final?.["ePQ"]).toBe(pairing(input.a, input.b));
        expect(final?.["eHH"]).toBe(pairing(1, 1));
        expect(final?.["leftBilinear"]).toBe(pairing((2 * input.a) % Q, input.b));
        expect(final?.["rightBilinear"]).toBe(modp(pairing(input.a, input.b) ** 2));
        expect(final?.["ok"]).toBe(true);
    });

    it("satisfies bilinearity, symmetry, and nondegeneracy for every exponent pair", () => {
        for (let a = 0; a < Q; a += 1) {
            for (let b = 0; b < Q; b += 1) {
                const final = [...mod.run({ a, b })].pop()?.meta;
                expect(final?.["bilinear"]).toBe(true);
                expect(final?.["symmetric"]).toBe(true);
                expect(final?.["nonDegenerate"]).toBe(true);
                expect(final?.["ePQ"]).toBe(pairing(b, a));
            }
        }
    });

    it("terminates cleanly", () => {
        const generator = mod.run(mod.defaultInput);
        let count = 0;
        for (const _frame of generator) count += 1;
        expect(count).toBeGreaterThan(0);
        expect(generator.next().done).toBe(true);
    });
});
