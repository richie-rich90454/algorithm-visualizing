/**
 * hidden-subgroup-problem.ts - Abelian Hidden Subgroup Problem on Z_N
 *
 * ---------------------------------------------------------------------------
 * What it does
 * ---------------------------------------------------------------------------
 * The hidden subgroup problem asks for a subgroup H that is invisible to an
 * oracle f: f(x) equals f(y) exactly when x minus y lies in H. For a cyclic
 * group Z_N the solution is the same Fourier sampling routine that solves
 * Simon's problem on a different group: prepare a uniform superposition, query
 * the oracle, measure the oracle register to collapse onto a coset of H, apply
 * the quantum Fourier transform, and read a character that is orthogonal to H.
 * Several samples reveal the dual subgroup and hence H itself.
 *
 * ---------------------------------------------------------------------------
 * Scope of the model
 * ---------------------------------------------------------------------------
 * This is an exact state-vector simulation for the abelian group Z_N with N at
 * most sixteen and a hidden subgroup H generated by a divisor k of N. It uses
 * the oracle f(x) = x mod k and exact complex amplitudes. Non-abelian hidden
 * subgroups, oracle noise, and finite sample statistics are not modeled.
 *
 * ---------------------------------------------------------------------------
 * Complexity
 * ---------------------------------------------------------------------------
 *   Time: O(N^2) for the direct Fourier transform over N points
 *   Space: O(N) for the amplitude vector
 *
 * ---------------------------------------------------------------------------
 * Visualization mapping
 * ---------------------------------------------------------------------------
 *   - Bars show the measurement probability of each Fourier basis label j.
 *   - Hidden-subgroup-orthogonal labels are highlighted after the transform.
 *   - The final frame reports the recovered subgroup generator.
 */

import type { AlgorithmModule, VisualEntity, VisualFrame } from "@/types";

interface HspInput {
    n?: number;
    k?: number;
    y?: number;
}

function bars(probabilities: number[], highlight: number[]): VisualEntity[] {
    return probabilities.map((probability, index) => ({
        id: `fourier-${index}`,
        type: "bar" as const,
        label: `j=${index}: ${probability.toFixed(3)}`,
        value: probability,
        state: (highlight.includes(index) ? "active" : probability > 1e-12 ? "visited" : "idle") as VisualEntity["state"],
        x: index,
        y: 0,
        width: 0,
        height: 0,
        metadata: { index, probability, label: index },
    }));
}

function gcd(a: number, b: number): number {
    let x = Math.abs(a);
    let y = Math.abs(b);
    while (y !== 0) {
        const t = y;
        y = x % y;
        x = t;
    }
    return x;
}

/** Exact Fourier amplitudes of a uniform superposition over the coset y + <k>. */
function fourierAmplitudes(n: number, k: number, y: number): Array<{ re: number; im: number }> {
    const d = n / k;
    const scale = 1 / Math.sqrt(n * d);
    const out: Array<{ re: number; im: number }> = [];
    for (let j = 0; j < n; j += 1) {
        let re = 0;
        let im = 0;
        for (let m = 0; m < d; m += 1) {
            const x = (y + m * k) % n;
            const angle = (2 * Math.PI * j * x) / n;
            re += Math.cos(angle);
            im += Math.sin(angle);
        }
        out.push({ re: re * scale, im: im * scale });
    }
    return out;
}

function probabilities(amplitudes: Array<{ re: number; im: number }>): number[] {
    return amplitudes.map((a) => a.re * a.re + a.im * a.im);
}

function* run(input: unknown): Generator<VisualFrame, void, unknown> {
    const task = (input as HspInput | null) ?? {};
    const n = Math.max(2, Math.min(16, typeof task.n === "number" ? task.n : 8));
    let k = typeof task.k === "number" ? task.k : 2;
    if (k < 1 || k > n || n % k !== 0) {
        k = 2;
    }
    const y = typeof task.y === "number" ? ((task.y % n) + n) % n : 0;
    const d = n / k;

    const uniform = new Array<number>(n).fill(1 / n);
    const coset = new Array<number>(n).fill(0);
    for (let m = 0; m < d; m += 1) {
        coset[(y + m * k) % n] = 1 / d;
    }

    const amplitudes = fourierAmplitudes(n, k, y);
    const measured = probabilities(amplitudes);
    const support = measured
        .map((p, index) => (p > 1e-9 ? index : -1))
        .filter((index) => index >= 0);

    let common = n;
    for (const j of support) {
        common = gcd(common, j);
    }
    const recoveredK = common === 0 ? n : n / common;
    const subgroup = Array.from({ length: d }, (_, m) => (m * recoveredK) % n);

    let step = 0;
    yield {
        stepNumber: step,
        entities: bars(uniform, []),
        edges: [],
        description: `Hidden subgroup on Z_${n}: prepare a uniform superposition over all ${n} group elements.`,
        codeLineNumber: 0,
        layout: "array",
        meta: { n, k, d, step: 0 },
    };
    step += 1;

    yield {
        stepNumber: step,
        entities: bars(coset, support),
        edges: [],
        description: `Query the oracle and read the coset representative ${y}; the first register collapses onto a uniform coset of size ${d}.`,
        codeLineNumber: 2,
        layout: "array",
        meta: { n, k, d, step: 1, y },
    };
    step += 1;

    yield {
        stepNumber: step,
        entities: bars(measured, support),
        edges: [],
        description: `Apply the Fourier transform over Z_${n}: only ${support.length} labels carry probability, all multiples of ${common}.`,
        codeLineNumber: 3,
        layout: "array",
        meta: { n, k, d, step: 2, support: support.join(","), common },
    };
    step += 1;

    yield {
        stepNumber: step,
        entities: bars(measured, support),
        edges: [],
        description: `Measuring returns a label orthogonal to the hidden subgroup; the labels share greatest common divisor ${common}.`,
        codeLineNumber: 4,
        layout: "array",
        meta: { n, k, d, step: 3, common, support: support.join(","), total: measured.reduce((a, b) => a + b, 0) },
    };
    step += 1;

    yield {
        stepNumber: step,
        entities: bars(measured, support),
        edges: [],
        description: `Recovered generator ${recoveredK}: the hidden subgroup is {${subgroup.join(", ")}} inside Z_${n}.`,
        codeLineNumber: 5,
        layout: "array",
        meta: { n, k, d, step: 4, recoveredK, subgroup: subgroup.join(","), correct: recoveredK === k ? 1 : 0 },
    };
}

