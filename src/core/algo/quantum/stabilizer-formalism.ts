/**
 * stabilizer-formalism.ts - Stabilizer Tableau Simulation (Exact Small Model)
 *
 * ---------------------------------------------------------------------------
 * What it does
 * ---------------------------------------------------------------------------
 * The stabilizer formalism describes a quantum state not by its amplitudes but
 * by the Pauli operators that leave it unchanged. An n-qubit stabilizer state
 * has exactly n independent commuting generators, and their products form a
 * group of 2^n stabilizers that uniquely determine the state. Clifford gates
 * such as Hadamard and controlled-NOT permute the generators, so simulating
 * them costs only polynomial work instead of tracking all amplitudes.
 *
 * This module keeps generators in the real Pauli subgroup generated by X and Z
 * and updates them under H and CNOT. It then derives the state by projecting
 * onto the common plus-one eigenspace and reading off a nonzero column of the
 * projector. The model is exact for at most three qubits and for Clifford
 * circuits built from H and CNOT only; it intentionally omits the phase gate
 * and Y operators, which would require imaginary phases, and it does not
 * simulate non-Clifford gates or noisy states.
 *
 * ---------------------------------------------------------------------------
 * Complexity
 * ---------------------------------------------------------------------------
 *   Time:  O(4^n) to build the projector from the 2^n stabilizer group
 *   Space: O(4^n) for the projector matrix
 *
 * ---------------------------------------------------------------------------
 * Visualization mapping
 * ---------------------------------------------------------------------------
 *   - A grid row per generator shows its per-qubit Pauli symbol and sign.
 *   - A row updated by the current gate is yellow; the final table is green.
 *   - The metadata carries the generators, group size, and derived amplitudes.
 */

import type { AlgorithmModule, EntityState, VisualEntity, VisualFrame } from "@/types";

interface Pauli {
    x: boolean[];
    z: boolean[];
    sign: number;
}

interface Gate {
    type?: string;
    q?: number;
    control?: number;
    target?: number;
}

interface StabilizerInput {
    n?: number;
    initial?: "zero" | "plus" | "bell";
    gates?: Gate[];
}

function identity(n: number): Pauli {
    return { x: new Array<number>(n).fill(0).map(() => false), z: new Array<number>(n).fill(0).map(() => false), sign: 1 };
}

function generator(initial: string, n: number): Pauli[] {
    if (initial === "plus") {
        return Array.from({ length: n }, (_, q) => {
            const p = identity(n);
            p.x[q] = true;
            return p;
        });
    }
    if (initial === "bell" && n >= 2) {
        const gx = identity(n);
        gx.x[0] = true;
        gx.x[1] = true;
        const gz = identity(n);
        gz.z[0] = true;
        gz.z[1] = true;
        const rest: Pauli[] = [];
        for (let q = 2; q < n; q += 1) {
            const z = identity(n);
            z.z[q] = true;
            rest.push(z);
        }
        return [gx, gz, ...rest];
    }
    return Array.from({ length: n }, (_, q) => {
        const p = identity(n);
        p.z[q] = true;
        return p;
    });
}

/** Multiply two real Pauli strings, including the Z/X anticommutation sign. */
function multiply(a: Pauli, b: Pauli): Pauli {
    let sign = a.sign * b.sign;
    for (let q = 0; q < a.x.length; q += 1) {
        if (a.z[q] && b.x[q]) sign *= -1;
    }
    return {
        x: a.x.map((v, q) => Boolean(Number(v) ^ Number(b.x[q]))),
        z: a.z.map((v, q) => Boolean(Number(v) ^ Number(b.z[q]))),
        sign,
    };
}

/** Conjugate a generator by a Hadamard on qubit q: X and Z swap. */
function applyH(p: Pauli, q: number): Pauli {
    const next: Pauli = { x: [...p.x], z: [...p.z], sign: p.sign };
    const tmp = next.x[q]!;
    next.x[q] = next.z[q]!;
    next.z[q] = tmp;
    return next;
}

/** Conjugate a generator by CNOT: x_t xor= x_c and z_c xor= z_t. */
function applyCnot(p: Pauli, control: number, target: number): Pauli {
    const next: Pauli = { x: [...p.x], z: [...p.z], sign: p.sign };
    next.x[target] = Boolean(Number(next.x[target]) ^ Number(next.x[control]));
    next.z[control] = Boolean(Number(next.z[control]) ^ Number(next.z[target]));
    return next;
}

function bitsToInt(bits: boolean[]): number {
    return bits.reduce((v, bit, q) => v | (bit ? 1 << q : 0), 0);
}

function parity(a: number, b: number): number {
    let v = a & b;
    let count = 0;
    while (v !== 0) {
        count ^= 1;
        v &= v - 1;
    }
    return count;
}

/** Derive the state vector by projecting onto the common +1 eigenspace. */
function deriveState(generators: Pauli[], n: number): number[] {
    const group: Pauli[] = [identity(n)];
    for (const g of generators) {
        const extended = group.map((item) => multiply(item, g));
        group.push(...extended);
    }
    const dim = 1 << n;
    const projector = Array.from({ length: dim }, () => new Array<number>(dim).fill(0));
    for (const g of group) {
        const xmask = bitsToInt(g.x);
        const zmask = bitsToInt(g.z);
        for (let col = 0; col < dim; col += 1) {
            const phase = g.sign * (parity(zmask, col) ? -1 : 1);
            const row = col ^ xmask;
            projector[row]![col] = projector[row]![col]! + phase / group.length;
        }
    }
    let bestCol = 0;
    let bestNorm = -1;
    for (let col = 0; col < dim; col += 1) {
        let norm = 0;
        for (let row = 0; row < dim; row += 1) norm += projector[row]![col]! ** 2;
        if (norm > bestNorm) {
            bestNorm = norm;
            bestCol = col;
        }
    }
    const scale = bestNorm > 0 ? 1 / Math.sqrt(bestNorm) : 0;
    return projector.map((row) => row[bestCol]! * scale);
}

function pauliString(p: Pauli): string {
    return `${p.sign > 0 ? "+" : "-"}${p.x.map((x, q) => (x ? (p.z[q] ? "Y" : "X") : p.z[q] ? "Z" : "I")).join("")}`;
}

function makeCells(generators: Pauli[], n: number, active: number, done: boolean): VisualEntity[] {
    const entities: VisualEntity[] = [];
    generators.forEach((p, row) => {
        entities.push({
            id: `cell-${row}-sign`,
            type: "cell" as const,
            label: p.sign > 0 ? "+" : "-",
            value: p.sign,
            state: (done ? "sorted" : row === active ? "comparing" : "idle") as EntityState,
            x: 0,
            y: 0,
            width: 0,
            height: 0,
            metadata: { row, col: 0 },
        });
        for (let q = 0; q < n; q += 1) {
            entities.push({
                id: `cell-${row}-${q + 1}`,
                type: "cell" as const,
                label: p.x[q] ? (p.z[q] ? "Y" : "X") : p.z[q] ? "Z" : "I",
                value: pauliString(p),
                state: (done ? "sorted" : row === active ? "comparing" : "idle") as EntityState,
                x: 0,
                y: 0,
                width: 0,
                height: 0,
                metadata: { row, col: q + 1 },
            });
        }
    });
    return entities;
}

/** The stabilizer formalism generator. */
function* run(input: unknown): Generator<VisualFrame, void, unknown> {
    const task = (input as StabilizerInput | null) ?? {};
    const n = typeof task.n === "number" ? Math.max(1, Math.min(3, Math.floor(task.n))) : 2;
    const initial = task.initial === "plus" || task.initial === "bell" ? task.initial : "zero";
    const gates: Gate[] = Array.isArray(task.gates) ? task.gates.slice(0, 8) : [{ type: "H", q: 0 }];
    let generators = generator(initial, n);
    let step = 0;

    const frame = (description: string, line: number, active: number, done = false): VisualFrame => {
        const state = deriveState(generators, n);
        return {
            stepNumber: step++,
            entities: makeCells(generators, n, active, done),
            edges: [],
            description,
            codeLineNumber: line,
            layout: "grid",
            meta: {
                n,
                rows: generators.length,
                cols: n + 1,
                generators: generators.map(pauliString),
                groupSize: 2 ** generators.length,
                amplitudes: state,
                done,
            },
        };
    };

    yield frame(`Initialize ${n} qubits with ${generators.length} stabilizer generators (${initial}).`, 0, -1);

    for (let gi = 0; gi < gates.length; gi += 1) {
        const gate = gates[gi]!;
        if (gate.type === "H" && typeof gate.q === "number" && gate.q >= 0 && gate.q < n) {
            generators = generators.map((p) => applyH(p, gate.q!));
            yield frame(`Conjugate every generator by Hadamard on qubit ${gate.q}: X and Z swap.`, 2, gi % generators.length);
        } else if (
            gate.type === "CNOT" &&
            typeof gate.control === "number" &&
            typeof gate.target === "number" &&
            gate.control >= 0 && gate.control < n && gate.target >= 0 && gate.target < n &&
            gate.control !== gate.target
        ) {
            generators = generators.map((p) => applyCnot(p, gate.control!, gate.target!));
            yield frame(`Conjugate every generator by CNOT from ${gate.control} to ${gate.target}.`, 3, gi % generators.length);
        } else {
            yield frame(`Skipped invalid gate ${gi + 1}.`, 4, -1);
        }
    }

    yield frame(`Final tableau has ${generators.length} generators and a ${2 ** generators.length}-element stabilizer group.`, 5, -1, true);
}

